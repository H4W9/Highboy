// Pancake shim for TinyUSB's <class/hid/hid_device.h>.
//
// The ESP32-C5 has no USB-OTG peripheral, so esp_tinyusb is not built on the
// Pancake target. bad_usb.c (which used the TinyUSB device API) is stubbed,
// but ducky_parser.c / hid_layouts.c only need the standard USB HID keyboard
// usage IDs and modifier bitmasks to keep compiling (the keymaps are still
// parsed for display; nothing is actually sent). These are standard USB HID
// Usage Table values, not TinyUSB code.

